function escapeHtmlAttribute(value: string): string {
  return value.replace(/[&<>"']/g, (character) => {
    const entities: Record<string, string> = {
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#39;",
    };
    return entities[character];
  });
}

function updateGeronIsiLink(html: string, linkText: string, href: string): string {
  const escapedHref = escapeHtmlAttribute(href);
  return html.replace(/<a\b([^>]*)>([\s\S]*?)<\/a>/gi, (anchor, attributes: string, contents: string) => {
    if (contents.replace(/<[^>]*>/g, "").trim() !== linkText) return anchor;

    const hrefAttribute = /\bhref\s*=\s*(["'])(.*?)\1/i;
    if (hrefAttribute.test(attributes)) {
      return `<a${attributes.replace(hrefAttribute, `href="${escapedHref}"`)}>${contents}</a>`;
    }

    return `<a${attributes} href="${escapedHref}">${contents}</a>`;
  });
}

export function renderGeronIsiHtml(
  html: string,
  padding: string,
  prescribingInformationUrl: string,
  medicationGuideUrl: string,
): string {
  const linkedHtml = updateGeronIsiLink(
    updateGeronIsiLink(html, "Prescribing Information", prescribingInformationUrl),
    "Medication Guide",
    medicationGuideUrl,
  );
  const safePadding = escapeHtmlAttribute(padding);
  return `<table role="presentation" width="100%" cellspacing="0" cellpadding="0" border="0"><tbody><tr><td style="padding:${safePadding};">${linkedHtml}</td></tr></tbody></table>`;
}
